#include "libft.h"

void	ft_putendl_fd(char *s, int fd)
{
	int	i;

	i = 0;
	while (s[i])
	{
		write(fd, &s[i], ft_strlen(s));
		i++;
	}
	write(fd, "\n", 1);
}
